package main

import (
	"log"
	"net/http"
	"os"
	"time"

	"github.com/gorilla/mux"
	"github.com/joho/godotenv"
	httpSwagger "github.com/swaggo/http-swagger"
	"go.uber.org/zap"

	"teste/config"
	_ "teste/docs" // docs is generated by Swag CLI
	"teste/handlers"
)

